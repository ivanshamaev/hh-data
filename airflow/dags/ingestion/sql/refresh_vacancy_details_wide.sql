-- Постобработка: разбор raw.vacancy_details.payload в широкую таблицу raw.vacancy_details_wide.
-- Отсутствующие поля дают NULL.
INSERT INTO raw.vacancy_details_wide (
    id, name,
    area_id, area_name, area_url,
    type_id, type_name,
    salary_from, salary_to, salary_currency, salary_gross,
    address_raw, address_city, address_street, address_building, address_lat, address_lng,
    address_metro_station_name,
    employer_id, employer_name, employer_url, employer_logo_240,
    schedule_id, schedule_name,
    employment_id, employment_name,
    experience_id, experience_name,
    published_at, created_at, initial_created_at,
    alternate_url, description, description_clean, key_skills,
    premium, archived, has_test,
    billing_type_id, billing_type_name,
    employment_form_id, employment_form_name,
    work_schedule_by_days, work_schedule_by_days_name,
    working_hours, working_hours_name,
    professional_roles, professional_roles_name,
    response_letter_required,
    updated_at
)
SELECT
    d.id,
    d.payload->>'name',
    d.payload->'area'->>'id',
    d.payload->'area'->>'name',
    d.payload->'area'->>'url',
    d.payload->'type'->>'id',
    d.payload->'type'->>'name',
    (d.payload->'salary'->>'from')::numeric,
    (d.payload->'salary'->>'to')::numeric,
    d.payload->'salary'->>'currency',
    (d.payload->'salary'->>'gross')::boolean,
    d.payload->'address'->>'raw',
    d.payload->'address'->>'city',
    d.payload->'address'->>'street',
    d.payload->'address'->>'building',
    (d.payload->'address'->>'lat')::numeric,
    (d.payload->'address'->>'lng')::numeric,
    COALESCE(
        d.payload->'address'->'metro'->>'station_name',
        d.payload->'address'->'metro_stations'->0->>'station_name'
    ),
    d.payload->'employer'->>'id',
    d.payload->'employer'->>'name',
    d.payload->'employer'->>'url',
    d.payload->'employer'->'logo_urls'->>'240',
    d.payload->'schedule'->>'id',
    d.payload->'schedule'->>'name',
    d.payload->'employment'->>'id',
    d.payload->'employment'->>'name',
    d.payload->'experience'->>'id',
    d.payload->'experience'->>'name',
    (d.payload->>'published_at')::timestamptz,
    (d.payload->>'created_at')::timestamptz,
    (d.payload->>'initial_created_at')::timestamptz,
    d.payload->>'alternate_url',
    d.payload->>'description',
    trim(regexp_replace(regexp_replace(d.payload->>'description', '<[^>]+>', '', 'g'), '\s+', ' ', 'g')),
    d.payload->'key_skills',
    (d.payload->>'premium')::boolean,
    (d.payload->>'archived')::boolean,
    (d.payload->>'has_test')::boolean,
    d.payload->'billing_type'->>'id',
    d.payload->'billing_type'->>'name',
    d.payload->'employment_form'->>'id',
    d.payload->'employment_form'->>'name',
    d.payload->'work_schedule_by_days',
    (SELECT string_agg(elem->>'name', ', ' ORDER BY ord) FROM jsonb_array_elements(d.payload->'work_schedule_by_days') WITH ORDINALITY AS t(elem, ord)),
    d.payload->'working_hours',
    (SELECT string_agg(elem->>'name', ', ' ORDER BY ord) FROM jsonb_array_elements(d.payload->'working_hours') WITH ORDINALITY AS t(elem, ord)),
    d.payload->'professional_roles',
    (SELECT string_agg(elem->>'name', ', ' ORDER BY ord) FROM jsonb_array_elements(d.payload->'professional_roles') WITH ORDINALITY AS t(elem, ord)),
    (d.payload->>'response_letter_required')::boolean,
    now()
FROM raw.vacancy_details d
ON CONFLICT (id) DO UPDATE SET
    name = EXCLUDED.name,
    area_id = EXCLUDED.area_id,
    area_name = EXCLUDED.area_name,
    area_url = EXCLUDED.area_url,
    type_id = EXCLUDED.type_id,
    type_name = EXCLUDED.type_name,
    salary_from = EXCLUDED.salary_from,
    salary_to = EXCLUDED.salary_to,
